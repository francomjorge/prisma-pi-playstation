#!/usr/bin/env python3
"""Cook a deterministic 256-glyph CP437 8x8 asset.

Input is a raw 8x8 CP437 ROM: exactly 2048 bytes, glyph order 0x00..0xFF,
8 row bytes per glyph. Output is the same canonical representation plus a
Rust include file. No image library is required.
"""
from pathlib import Path
import argparse, hashlib

p = argparse.ArgumentParser()
p.add_argument("source", type=Path)
p.add_argument("--out", type=Path, default=Path("build/assets/cp437_8x8.bin"))
p.add_argument("--rust", type=Path, default=Path("build/assets/cp437_8x8.rs"))
a = p.parse_args()
raw = a.source.read_bytes()
if len(raw) != 256 * 8:
    raise SystemExit(f"CP437 source must be exactly 2048 bytes, got {len(raw)}")
a.out.parent.mkdir(parents=True, exist_ok=True)
a.rust.parent.mkdir(parents=True, exist_ok=True)
a.out.write_bytes(raw)
rows=[]
for i in range(0,len(raw),16):
    rows.append("    " + ", ".join(f"0x{x:02X}" for x in raw[i:i+16]) + ",")
a.rust.write_text("// Generated by tools/cook_cp437.py; 256 CP437 glyphs, 8x8, 8 bytes/glyph.\n" +
                  "pub const CP437_8X8: [u8; 2048] = [\n" + "\n".join(rows) + "\n];\n")
print(f"CP437 cooked: {a.out} (2048 bytes) sha256={hashlib.sha256(raw).hexdigest()}")
